#!/usr/bin/env python3
"""make_packs.py - the six EXPANSION PACKS as BPS patches that go on in any order, alone or together.

THE LAYOUT  Each pack owns a fixed slot at the top of the ROM (SLOTS below; source/packslots.h tells the game). The link (tools/bore.ld INCLUDEs
            tools/packs.ld, written by `make_packs.py ld`) puts the pack's header first in its slot (expand.h XP_HD), then the code and the
            tables of the headers listed in PACKS below (by -ffunction-sections / -fdata-sections name), then a 4-byte word. String
            literals stay in the base game (main.c is one translation unit: a literal lives once, wherever it was first used); the text that
            is a pack's own (its mission table, its story pages) is in named arrays, so it rides in the slot. What a pack keeps
            in the base game (KEEP: its save chunk, the little checks the life game asks every step) stays in the base ROM.
THE SPLIT   `make_packs.py split bore.elf bore.gba bore-base.gba packs/` takes the complete ROM (bore.gba, every pack in: the game as you play
            it), writes the base ROM (bore-base.gba, every slot blank, 0xFF) and one .bps per pack (base -> base + that pack).
ANY ORDER   A BPS patch checks the CRC32 of the ROM it is given. So every slot's last word is chosen to cancel the slot out of the CRC32: the
            ROM's CRC32 is the same with any set of packs in it. Each patch then sees exactly the checksum it expects whichever packs are
            already there, and writes only its own slot (SourceRead outside it, its own bytes inside), so the packs commute: any order, any
            subset, and patching a pack twice changes nothing. `split` checks this: all 64 sets of packs, and the six in several orders.
Run by the Makefile. Needs nothing but Python 3 (zlib).
"""
import os, re, sys, zlib, itertools, random

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ROM0 = 0x08000000
# the slots: where each pack lives and how big it may grow (BORTUA FIGHTER's polygon fighters take 3.4 MB of art). The base game has
# everything below the first (24 MB); the last megabyte, 0x09F00000 up, is kept for the packs still to come.
SLOTS = [(0x09800000, 0x080000), (0x09880000, 0x100000), (0x09980000, 0x080000), (0x09A00000, 0x400000), (0x09E00000, 0x080000), (0x09E80000, 0x080000)]
SLOTS_END = 0x09F00000
FILES = ['BORE-EP1-BORE-OUT-MAN.bps', 'BORE-EP2-BOREZIES.bps', 'BORE-EP3-WORLD-WAR-BORE.bps',
         'BORE-EP4-BORTUA-FIGHTER.bps', 'BORE-EP7-BOREAGOTCHI.bps', 'BORE-EP8-BOREPILOGUE.bps']
TITLES = ['BORE-OUT MAN!', 'BOREZIES!', 'WORLD WAR BORE', 'BORTUA FIGHTER', 'BOREagotchi!', 'BOREpilogue']

# pack -> (headers whose functions and tables go in the slot, names that stay in the base game, extra names that go in the slot)
PACKS = [
    (['space.h'], [], ['xmSpace']),
    (['horde.h', 'arena.h', 'arenas.h'],
     ['hzSpeedPct', 'hzToughPct', 'hzBiteMul', 'hzCureRule', 'hzDmgPct', 'hzCap', 'hzCapMax', 'hzLoad', 'hzReset', 'hzoN', 'hzoDef', 'hzSum'],
     ['xmZomb', 'xz1In', 'xz1Out', 'xz2In', 'xz2Out', 'xz3In', 'xz3Out', 'xz4In', 'xz4Out', 'xz5In', 'xz5Out']),
    ([], [], ['xmWar']),
    (['bortua.h', 'bortuaart.h', 'bortuawtf.h'], ['bfSum', 'bfSave', 'bfLoadFrom', 'bfLoad', 'sgEncArcade'], ['xmFight', 'bfaArt']),   # (bfaArt: the fighters' and the arena's art, .incbin'd into .rodata.bfaArt)
    (['gotchi.h'], ['goSum', 'goPack', 'goUnpack', 'goClear', 'goSave', 'goLoad', 'goHas', 'goNew', 'goNeeds', 'goTick', 'goMinute',
                    'sgEncGotchi', 'goNames', 'goStNm', 'goFormNm'], ['xmGotchi']),
    ([], [], ['xmEpi']),
]

def names_in(header):   # every top-level function and table a header defines
    s = open(os.path.join(ROOT, 'source', header)).read()
    out = []
    for m in re.finditer(r'^(?:XPF\s+)?static\s+(?:inline\s+)?(?:const\s+)?[\w\s\*]*?\b([A-Za-z_]\w*)\s*\(', s, re.M):
        out.append(m.group(1))
    for m in re.finditer(r'^static\s+const\s+[\w\s\*]*?\b([A-Za-z_]\w*)\s*\[', s, re.M):
        out.append(m.group(1))
    for m in re.finditer(r'^static\s+const\s+char\s*\*\s*const\s+([A-Za-z_]\w*)\s*\[', s, re.M):
        out.append(m.group(1))
    return out

def pack_names(p):
    hs, keep, extra = PACKS[p]
    n = []
    for h in hs:
        for x in names_in(h):
            if x not in keep and x not in n: n.append(x)
    for x in extra:
        if x not in n: n.append(x)
    return n

def write_ld():
    H = ['// packslots.h - GENERATED by tools/make_packs.py ld: where each expansion pack\'s slot is (tools/packs.ld puts the packs there). Do not edit.']
    for p, (a, n) in enumerate(SLOTS): H.append('#define XP_AT%d 0x%08Xu   // %s, %d KB' % (p, a, TITLES[p], n // 1024))
    H.append('#define XP_SLOTS_END 0x%08Xu' % SLOTS_END)
    open(os.path.join(ROOT, 'source', 'packslots.h'), 'w').write('\n'.join(H) + '\n')
    L = ['/* packs.ld - GENERATED by tools/make_packs.py ld: the six expansion packs, each in its own fixed slot (source/packslots.h).',
         '   INCLUDEd by tools/bore.ld before .text, so these input sections are claimed here and nowhere else. Do not edit. */']
    for p in range(6):
        pats = []
        for x in pack_names(p):
            pats += ['.text.%s' % x, '.text.%s.*' % x, '.rodata.%s' % x]   # (never .rodata.NAME.str*: in one translation unit a string literal is
            # kept once, in the string section of whichever function used it first, so the base game's own strings would be swept into the slot too)
        L.append('\t.xp%d 0x%08X : {' % (p, SLOTS[p][0]))
        L.append('\t\tKEEP(*(.xphd%d))' % p)
        for i in range(0, len(pats), 8): L.append('\t\t*(' + ' '.join(pats[i:i + 8]) + ')')
        L.append('\t\t. = ALIGN(4); __xp%d_comp = .; KEEP(*(.xpc%d))' % (p, p))
        L.append('\t} >xprom = 0xff')
        L.append('\tASSERT(SIZEOF(.xp%d) <= 0x%X, "pack %d is over its slot")' % (p, SLOTS[p][1], p))
    open(os.path.join(ROOT, 'tools', 'packs.ld'), 'w').write('\n'.join(L) + '\n')

# ---------------------------------------------------------------- BPS (beat's patch format)
def num(n):
    o = bytearray()
    while True:
        x = n & 0x7F; n >>= 7
        if n == 0: o.append(0x80 | x); return bytes(o)
        o.append(x); n -= 1

def bps_make(size, lo, hi, tgt, crc, meta):   # base -> base with tgt[lo:hi]: SourceRead outside, the slot's own bytes inside
    o = bytearray(b'BPS1') + num(size) + num(size) + num(len(meta)) + meta
    def act(cmd, n): return num(((n - 1) << 2) | cmd)
    if lo: o += act(0, lo)
    i = lo; lit = bytearray(); tr = 0   # tr: where the last TargetCopy left off (BPS offsets are relative to it)
    def flush():
        nonlocal lit
        if lit: o.extend(act(1, len(lit)) + lit); lit = bytearray()
    while i < hi:   # TargetRead, with long runs as a TargetCopy of the run's first byte (only from inside the slot: other slots are never read)
        j = i
        while j < hi and tgt[j] == tgt[i]: j += 1
        if j - i >= 8:
            lit.append(tgt[i]); flush()
            d = i - tr; o += act(3, j - i - 1) + num((abs(d) << 1) | (d < 0)); tr = i + (j - i - 1)
            i = j
        else:
            lit += tgt[i:j]; i = j
    flush()
    if hi < size: o += act(0, size - hi)
    o += crc.to_bytes(4, 'little') + crc.to_bytes(4, 'little')
    o += zlib.crc32(o).to_bytes(4, 'little')
    return bytes(o)

def bps_apply(patch, src):   # a plain beat-spec patcher (with every check a real one makes), for the self-test
    p = 0
    def rd():
        nonlocal p
        d, s = 0, 1
        while True:
            x = patch[p]; p += 1; d += (x & 0x7F) * s
            if x & 0x80: return d
            s <<= 7; d += s
    assert patch[:4] == b'BPS1'; p = 4
    ss, ts, ms = rd(), rd(), rd(); p += ms
    L = len(patch); scrc, tcrc, pcrc = (int.from_bytes(patch[L - 12 + 4 * k:L - 8 + 4 * k], 'little') for k in range(3))
    if zlib.crc32(patch[:-4]) != pcrc: raise ValueError('patch damaged')
    if len(src) != ss or zlib.crc32(src) != scrc: raise ValueError('not the ROM this patch is for')
    out = bytearray(ts); o = 0; sr = tr = 0
    while p < len(patch) - 12:
        d = rd(); c, n = d & 3, (d >> 2) + 1
        if c == 0: out[o:o + n] = src[o:o + n]; o += n
        elif c == 1: out[o:o + n] = patch[p:p + n]; p += n; o += n
        elif c == 2:
            e = rd(); sr += (-1 if e & 1 else 1) * (e >> 1); out[o:o + n] = src[sr:sr + n]; sr += n; o += n
        else:
            e = rd(); tr += (-1 if e & 1 else 1) * (e >> 1)
            for _ in range(n): out[o] = out[tr]; o += 1; tr += 1
    if zlib.crc32(out) != tcrc: raise ValueError('wrong result')
    return bytes(out)

# ---------------------------------------------------------------- CRC32 that a slot leaves alone
def crc_lin(buf, zcrc):   # the linear part of CRC32 over a fixed length: crc(x) = lin(x) ^ crc(zeros)
    return zlib.crc32(buf) ^ zcrc

def cancel(size, at, delta_at, delta):   # the 4 bytes at `at` that make the change (delta at delta_at) vanish from the CRC32
    z = bytearray(size); zc = zlib.crc32(z)
    z[delta_at:delta_at + len(delta)] = delta; want = crc_lin(z, zc); z[delta_at:delta_at + len(delta)] = bytes(len(delta))
    cols = []
    for b in range(32):
        z[at + b // 8] = 1 << (b % 8); cols.append(crc_lin(z, zc)); z[at + b // 8] = 0
    rows = [(cols[b], 1 << b) for b in range(32)]   # Gaussian elimination over GF(2): find bits whose columns XOR to `want`
    basis = []
    for v, m in rows:
        for bv, bm in basis:
            if v ^ bv < v: v ^= bv; m ^= bm
        if v: basis.append((v, m)); basis.sort(reverse=True)
    v, m = want, 0
    for bv, bm in basis:
        if v ^ bv < v: v ^= bv; m ^= bm
    if v: raise SystemExit('make_packs: cannot cancel the CRC (should never happen)')
    return m.to_bytes(4, 'little')

def symbols(elf):
    nm = os.environ.get('NM', 'arm-none-eabi-nm')
    out = {}
    for line in os.popen('%s %s' % (nm, elf)).read().split('\n'):
        p = line.split()
        if len(p) == 3: out[p[2]] = int(p[0], 16)
    return out

def split(elf, complete, base_out, packdir):
    sym = symbols(elf)
    full = bytearray(open(complete, 'rb').read())
    size = SLOTS_END - ROM0   # every ROM, with or without packs, is this long
    if len(full) > size: raise SystemExit('make_packs: the ROM is longer than the slots allow')
    full += b'\xff' * (size - len(full))
    base = bytearray(full)
    for p in range(6):
        lo = SLOTS[p][0] - ROM0; base[lo:lo + SLOTS[p][1]] = b'\xff' * SLOTS[p][1]
    crc = zlib.crc32(base)
    slots = []
    for p in range(6):
        lo = SLOTS[p][0] - ROM0; hi = lo + SLOTS[p][1]
        comp = sym['__xp%d_comp' % p] - ROM0
        assert lo < comp + 4 <= hi and full[comp:comp + 4] == b'\xff\xff\xff\xff', 'pack %d: its last word must still be blank' % p
        if full[lo:lo + 4] != b'BXPK': raise SystemExit('make_packs: pack %d has no header in its slot' % p)
        delta = bytes(a ^ 0xFF for a in full[lo:hi])
        c = cancel(size, comp, lo, delta)
        for k in range(4): full[comp + k] ^= c[k]
        slots.append((lo, hi))
        t = bytearray(base); t[lo:hi] = full[lo:hi]
        assert zlib.crc32(t) == crc, 'pack %d still changes the CRC' % p
    os.makedirs(packdir, exist_ok=True)
    patches = []
    for p, (lo, hi) in enumerate(slots):
        used = hi
        while used > lo and full[used - 1] == 0xFF: used -= 1
        meta = ('BORE expansion pack: %s. Patch bore-base.gba (the base game). Packs go on in any order, alone or together.' % TITLES[p]).encode()
        bp = bps_make(size, lo, hi, full, crc, meta)
        open(os.path.join(packdir, FILES[p]), 'wb').write(bp); patches.append(bp)
        print('make_packs: %-30s %7d B (pack %d uses %d of %d KB of its slot)' % (FILES[p], len(bp), p, (used - lo + 1023) // 1024, SLOTS[p][1] // 1024))
    open(base_out, 'wb').write(base); open(complete, 'wb').write(full)
    # the self-test: every set of packs in ascending order, then all six in a few other orders, against what it should be
    def expect(ps):
        t = bytearray(base)
        for q in ps: lo, hi = slots[q]; t[lo:hi] = full[lo:hi]
        return bytes(t)
    for n in range(64):
        ps = [q for q in range(6) if n >> q & 1]; r = bytes(base)
        for q in ps: r = bps_apply(patches[q], r)
        assert r == expect(ps), 'packs %s applied in order give the wrong ROM' % ps
    rng = random.Random(7); orders = [list(range(6))[::-1]] + [rng.sample(range(6), 6) for _ in range(6)]
    for o in orders:
        r = bytes(base)
        for q in o: r = bps_apply(patches[q], r)
        assert r == bytes(full), 'packs in the order %s give the wrong ROM' % o
    r = bps_apply(patches[1], bps_apply(patches[1], bytes(base))); assert r == expect([1]), 'a pack patched twice changes the ROM'
    print('make_packs: base %s (CRC32 %08X, the same with any packs); all 64 sets and %d orders check out' % (os.path.basename(base_out), crc, len(orders)))

if __name__ == '__main__':
    if len(sys.argv) >= 2 and sys.argv[1] == 'ld': write_ld()
    elif len(sys.argv) == 6 and sys.argv[1] == 'split': split(*sys.argv[2:])
    else: raise SystemExit(__doc__)

// PC-side baker: renders every item sprite exactly like the old in-game code did, and writes source/itemrom.h (const data for ROM).
// Built and run by tools/bake_items.sh. Needs only a plain C compiler (gcc / clang / tcc).
#include <stdio.h>
#include <stdint.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32;
#define RGB(r,g,b) ((u16)((r)|((g)<<5)|((b)<<10)))
static inline u16 shade(u16 c,int n){ int r=c&31,g=(c>>5)&31,b=(c>>10)&31; return RGB(r*n/16,g*n/16,b*n/16); }   // identical to main.c
#include "../source/itembake.h"
int main(int argc,char**argv){
    const char*out=argc>1?argv[1]:"itemrom.h"; FILE*f=fopen(out,"w"); if(!f){ perror(out); return 1; }
    bakeAll();
    // The sprites are 21 x 38 with large see-through margins, so only the OPAQUE SPAN of each row is stored (itemSpan: the first opaque column and one past the last), the rows of a sprite one after another
    // in itemPix, and itemOff[k] is where sprite k begins: about a third of the old 1.25 MB. blitItemO (items.h) walks it; a see-through pixel INSIDE a span is still stored (IKEY).
    static u8 span[NIV][IH][2]; long total=0; static u32 off[NIV];
    for(int k=0;k<NIV;k++){ off[k]=(u32)total; for(int j=0;j<IH;j++){ const u16*s=&bakeBuf[k][j][0]; int a=IW,b=0;
            for(int i=0;i<IW;i++) if(s[i]!=IKEY){ if(i<a) a=i; b=i+1; }
            if(a>=b) a=b=0;
            span[k][j][0]=(u8)a; span[k][j][1]=(u8)b; total+=b-a; } }
    fprintf(f,"// itemrom.h - GENERATED by tools/bake_items.sh (tools/bake_items.c + source/itembake.h). Do not edit.\n");
    fprintf(f,"// %d item sprites of %dx%d RGB555 (0x%04X = see-through), stored in ROM so they use no RAM: only the opaque span of each row (%ld pixels in all, %ld bytes).\n",NIV,IW,IH,IKEY,total,total*2);
    fprintf(f,"static const u16 itemPix[%ld] __attribute__((aligned(4)))={\n",total);
    long n=0; for(int k=0;k<NIV;k++) for(int j=0;j<IH;j++){ const u16*s=&bakeBuf[k][j][0]; for(int i=span[k][j][0];i<span[k][j][1];i++){ fprintf(f,"%s0x%X",n?(n%24?",":",\n"):"",s[i]); n++; } }
    fprintf(f,"};\n");
    fprintf(f,"static const u32 itemOff[%d]={",NIV); for(int k=0;k<NIV;k++) fprintf(f,"%s%u",k?(k%16?",":",\n"):"",off[k]); fprintf(f,"};   // where sprite k's rows begin in itemPix\n");
    // the first opaque column and one past the last, per sprite row (blitItem skips the see-through margins): a ROM table, so it uses no RAM
    fprintf(f,"static const u8 itemSpan[%d][%d][2]={\n",NIV,IH);
    for(int k=0;k<NIV;k++){ fprintf(f,"{"); for(int j=0;j<IH;j++) fprintf(f,"%s{%d,%d}",j?",":"",span[k][j][0],span[k][j][1]); fprintf(f,"},\n"); }
    fprintf(f,"};\n"); fclose(f);
    // proof: every pixel of every sprite is either inside its row's span (and then equal to the stored one) or see-through
    { long at=0; int bad=0; for(int k=0;k<NIV;k++) for(int j=0;j<IH;j++) for(int i=0;i<IW;i++){ u16 v=bakeBuf[k][j][i]; int in=i>=span[k][j][0]&&i<span[k][j][1]; if(!in&&v!=IKEY) bad++; (void)at; }
      if(bad){ fprintf(stderr,"%d pixels lie outside their spans\n",bad); return 1; }
      fprintf(stderr,"itemrom.h: %ld pixels in spans of %d x %d x %d = %d (%ld%%), %ld bytes of sprite data (was %d)\n",total,NIV,IW,IH,NIV*IW*IH,total*100/(NIV*IW*IH),total*2,NIV*IW*IH*2); }
    return 0;
}

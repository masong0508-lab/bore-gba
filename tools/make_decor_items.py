S('mDTbLeg','pDpTb','a'); S('mDTbEdge','pDpTb','b')
mat('mDTbTop','pDpTb',['aaaaaaaa','abbbbbba','abccccba','abbbbbba','abccccba','abbbbbba','abbbbbba','aaaaaaaa'])
box('bxDTable',[(0,1,1,2,0,6,['mDTbLeg']*5),(7,1,8,2,0,6,['mDTbLeg']*5),(0,6,1,7,0,6,['mDTbLeg']*5),(7,6,8,7,0,6,['mDTbLeg']*5),
               (0,1,8,7,6,8,['mDTbEdge']*4+['mDTbTop'])])

# chair: legs, a red cushion, a tall back (the back is at the rear, the seat faces the open floor like the sofa)
pal('pDpCh',[(8,4,2),(20,12,6),(27,6,6),(30,13,11)])
S('mDChLeg','pDpCh','a'); S('mDChWood','pDpCh','b'); S('mDChSeat','pDpCh','c')
mat('mDChSeatT','pDpCh',['cccccc','cdcccc','cccccc','cccccc','ccccdc','cccccc'])
mat('mDChBackF','pDpCh',['bbbbbb','bcccdb','bccccb','bcccdb','bbbbbb','bbbbbb','bbbbbb'])
box('bxDChair',[(1,2,2,3,0,3,['mDChLeg']*5),(6,2,7,3,0,3,['mDChLeg']*5),(1,6,2,7,0,3,['mDChLeg']*5),(6,6,7,7,0,3,['mDChLeg']*5),
               (1,2,7,7,3,5,['mDChSeat']*4+['mDChSeatT']),(1,2,7,3,5,12,['mDChWood','mDChWood','mDChBackF','mDChWood','mDChWood'])])

# desk: a drawer unit, a leg, a top, and a computer with a blue screen facing the open floor
pal('pDpDk',[(8,5,3),(20,13,7),(27,20,11),(5,5,8),(9,22,31),(22,27,31),(14,15,18)])
S('mDDkWood','pDpDk','b'); S('mDDkCase','pDpDk','d'); S('mDDkKeyS','pDpDk','g')
mat('mDDkTop','pDpDk',['aaaaaaaa','abbbbbba','abccccba','abbbbbba','abccccba','abbbbbba','abbbbbba','aaaaaaaa'])
mat('mDDkDraw','pDpDk',['aaa','abb','aab','aaa','abb'][:3]+['abb','aab'][:0])
mat('mDDkMon','pDpDk',['dddddd','deeeed','deffed','deeeed','deeeed','dddddd'])
mat('mDDkMonT','pDpDk',['dddddd','dgggdd'])
mat('mDDkKey','pDpDk',['gggggg','gdgdgd'])
box('bxDDesk',[(0,1,8,7,5,7,['mDDkWood']*4+['mDDkTop']),(0,1,3,7,0,5,['mDDkDraw','mDDkWood','mDDkWood','mDDkWood','mDDkWood']),(7,1,8,7,0,5,['mDDkWood']*5),
              (2,2,6,3,7,12,['mDDkMon','mDDkCase','mDDkCase','mDDkCase','mDDkMonT']),(3,2,5,4,7,8,['mDDkCase']*5),(2,4,6,6,7,8,['mDDkKey']*4+['mDDkKeyS'])])

# floor lamp: a dark base, a thin pole, a glowing yellow shade
pal('pDpLp',[(5,5,8),(12,12,15),(30,25,11),(31,31,23)])
S('mDLpBase','pDpLp','b'); S('mDLpPole','pDpLp','a')
mat('mDLpSh','pDpLp',['ccccc','cdddc','cdddc','cdddc','ccccc'])
mat('mDLpShT','pDpLp',['ddddd','dcccd','dcccd','dcccd','ddddd'])
box('bxDLamp',[(2,2,6,6,0,1,['mDLpBase']*5),(4,4,5,5,1,12,['mDLpPole']*5),(2,2,6,6,12,17,['mDLpSh']*4+['mDLpShT'])])

# houseplant: a terracotta pot and two tiers of leaves
pal('pDpPl',[(13,6,3),(24,12,6),(4,13,5),(9,22,9),(15,28,14)])
mat('mDPlPot','pDpPl',['bbbb','abba','abba','aaaa'])
mat('mDPlRimT','pDpPl',['aaaa','acca','acca','aaaa'])
mat('mDPlLeaf','pDpPl',['cdcdcd','dcecdc','cdcdce','ecdcdc','dcecdc'])

mat('mDPlLeaf2','pDpPl',['dce','cdd','ecd','dcc'])
mat('mDPlLeaf2T','pDpPl',['dced','cdcd','edcd','cded'])
box('bxDPlant',[(2,2,6,6,0,5,['mDPlPot']*4+['mDPlRimT']),(1,1,7,7,5,10,['mDPlLeaf']*4+['mDPlLeafT']),(2,2,6,6,10,14,['mDPlLeaf2']*4+['mDPlLeaf2T'])])

# dresser: a wooden chest of three drawers with gold knobs
pal('pDpDz',[(8,4,2),(21,13,6),(27,19,10),(31,26,9)])
mat('mDDrF','pDpDz',['aaaaaa','abbbba','abbdba','aaaaaa','abbbba','abbdba','aaaaaa','abbbba','abbdba','aaaaaa'])
S('mDDrS','pDpDz','b')
mat('mDDrT','pDpDz',['aaaaaa','abbbba','abccba','abccba','abbbba','aaaaaa'])
box('bxDDresser',[(1,2,7,7,0,10,['mDDrF','mDDrS','mDDrS','mDDrS','mDDrT'])])

# fireplace: a brick surround with a burning opening and a wooden mantel
pal('pDpFp',[(7,3,3),(20,8,6),(14,6,5),(2,2,3),(31,19,4),(31,28,10),(22,14,7),(11,6,3)])
mat('mDFpF','pDpFp',['bcbbcbbc','bbcbbcbb','bcbbcbbc','bddddddb','bdddeddb','bddeffdb','bdeffffd','bdddddddb'[:8],'bbbbbbbb','bcbbcbbc','bbcbbcbb','bcbbcbbc'])
S('mDFpS','pDpFp','b')
mat('mDFpMantF','pDpFp',['gggggggg','hhhhhhhh'])
S('mDFpMantS','pDpFp','g')
mat('mDFpMantT','pDpFp',['gggggggg']*6)
mat('mDFpTop','pDpFp',['bbbbbb','bcbcbc','bbbbbb','bcbcbc'])
box('bxDFire',[(0,3,8,8,0,12,['mDFpF','mDFpS','mDFpS','mDFpS','mDFpS']),(0,2,8,8,12,14,['mDFpMantF','mDFpMantS','mDFpMantS','mDFpMantS','mDFpMantT']),(1,5,7,8,14,18,['mDFpS']*4+['mDFpTop'])])

# kitchen counter: cabinet doors, a steel worktop with a sink and two hobs
pal('pDpKc',[(8,8,10),(24,24,26),(16,17,20),(8,18,29),(5,5,7),(28,10,6)])
mat('mDKcF','pDpKc',['aaaaaaaa','abbbbbba','abbbbbba','abbbbbba','abbaabba','abbbbbba','abbbbbba','aaaaaaaa'])
S('mDKcS','pDpKc','b')
mat('mDKcT','pDpKc',['aaaaaaaa','accccdda','accccdda','accccdda','abbbbbba','abeeebba','abbbbbba','aaaaaaaa'])
box('bxDCounter',[(0,1,8,7,0,8,['mDKcF','mDKcS','mDKcS','mDKcS','mDKcT'])])

here=os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here,'..','source','decorart.h'),'w').write('\n'.join(out)+'\n')
print('wrote source/decorart.h')

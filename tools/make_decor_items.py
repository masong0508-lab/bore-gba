#!/usr/bin/env python3
# make_decor_items.py - writes source/decorart.h: the LIVING AND DECOR pack (rug, dining table, chair, desk, floor lamp, houseplant,
# dresser, fireplace, kitchen counter). Same box + texture format as homeart.h (see itembake.h). Edit the art here, then run:
#   python3 tools/make_decor_items.py && sh tools/bake_items.sh
import os
out=['// decorart.h - GENERATED by tools/make_decor_items.py (LIVING AND DECOR pack). HOST-ONLY, included from itembake.h. Edit the script, not this file.']
def pal(nm,cols): out.append('static const u16 %s[%d]={%s};'%(nm,len(cols),','.join('RGB(%d,%d,%d)'%c for c in cols)))
def mat(nm,p,rows):
    w=len(rows[0]); assert all(len(r)==w for r in rows),(nm,rows)
    out.append('MAT(%s,%s,%d,%d,%s)'%(nm,p,w,len(rows),','.join('"%s"'%r for r in rows)))
def box(nm,bx):
    out.append('static const IBox %s[%d]={'%(nm,len(bx))+','.join('{%d,%d,%d,%d,%d,%d,{%s}}'%(b[:6]+(','.join('&'+m for m in b[6]),)) for b in bx)+'};')
def S(nm,p,c): mat(nm,p,[c])   # a plain colour

# rug: red with a gold border pattern, flat on the floor
pal('pDpRg',[(12,3,4),(23,7,8),(29,22,12)])

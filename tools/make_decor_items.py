mat('mDRgTop','pDpRg',['aaaaaaaa','abbbbbba','abcbbcba','abbccbba','abbccbba','abcbbcba','abbbbbba','aaaaaaaa'])
box('bxDRug',[(0,0,8,8,0,1,['mDRgSide']*4+['mDRgTop'])])

# dining table: four legs, a wooden top

// Host tool: bakes the pre-sampled floor tiles (flTab) into source/fltab.h so they live in ROM, not EWRAM.
// Build + run:  gcc -O1 -o /tmp/gen_fltab tools/gen_fltab.c && /tmp/gen_fltab > source/fltab.h
// Uses the very same maths as bakeTex() in main.c. Re-run it if you change a floor texture (flTex / flVs), CA, or the diamond shape.
#include <stdio.h>
#include <stdint.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32;
#define CA 8
#define CB (CA/2)
#define RGB(r,g,b) ((u16)((r)|((g)<<5)|((b)<<10)))
static u16 shade(u16 c,int n){ int r=c&31,g=(c>>5)&31,b=(c>>10)&31; return RGB(r*n/16,g*n/16,b*n/16); }
typedef struct { const char*nm; u16 c[4]; const char*p[8]; } Tex;
#define PN_FLAT  "00000000","00000000","00000000","00000000","00000000","00000000","00000000","00000000"
#define PN_NOISE "01000200","00020010","20001000","00100020","01000100","00200001","10002000","00010200"
#define PN_CONC  "00000100","02000000","00001000","00000020","00100000","00000002","20000000","00020100"
#define PN_TILE  "11111111","12001200","10001000","10001000","11111111","12001200","10001000","10001000"
#define PN_STEEL "00000000","01110000","00220000","00000000","00000000","00000111","00000022","00000000"
#define PN_GRASS_UNUSED 0
#include "../source/floorart.h"
static const u8 rTab0=CA;
static u16 tab[NFL][2][2*CB+1][2*CA+1];
int main(void){
    u8 hhT0[CA+1]; for(int at=0;at<=CA;at++) hhT0[at]=(u8)((rTab0/2)*(rTab0-at)/rTab0);
    for(int fl=0;fl<NFL;fl++){
        const Tex*t=&flTex[fl]; int vs=flVs[fl];
        for(int var=0;var<2;var++)for(int tt=-CA;tt<=CA;tt++){
            int hh=hhT0[tt<0?-tt:tt];
            for(int y=-hh;y<=hh;y++){
                int X=tt*CB+y*CA+CA*CB, Y=y*CA-tt*CB+CA*CB;
                int ta=X*8/(2*CA*CB), tb=Y*8/(2*CA*CB);
                if(ta<0)ta=0;
                if(ta>7)ta=7;
                if(tb<0)tb=0;
                if(tb>7)tb=7;
                u16 c=t->c[t->p[tb][ta]-'0']; if(var) c=shade(c,vs);
                tab[fl][var][y+CB][tt+CA]=c;
            }
        }
    }
    printf("// fltab.h - GENERATED by tools/gen_fltab.c (do not edit). The floor tiles pre-sampled onto the iso diamond: [floor][odd tile][row][column].\n");
    printf("// They live in ROM (const) instead of an 8.5 KB EWRAM buffer filled at start-up. Re-run the tool if a floor texture or CA changes.\n");
    printf("static const u16 flTab[NFL][2][2*CB+1][2*CA+1]={\n");
    for(int f=0;f<NFL;f++){ printf("{"); for(int v=0;v<2;v++){ printf("{"); for(int r=0;r<2*CB+1;r++){ printf("{"); for(int c=0;c<2*CA+1;c++) printf("%u%s",tab[f][v][r][c],c<2*CA?",":""); printf("}%s",r<2*CB?",":""); } printf("}%s",v<1?",":""); } printf("}%s\n",f<NFL-1?",":""); }
    printf("};\n");
    return 0; }

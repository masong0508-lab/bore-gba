#!/usr/bin/env python3
"""make_title_cc.py: the BORE CREATOR demo's title picture (source/titleimgcc.h) from the itch.io cover art (tools/cover_bore_gba.jpg).
A special treatment of the cover: the hand and the glass piece cropped tight, graded through a navy > cyan > hot pink > cream ramp (the creator's lab look),
reduced to 16 colours at 120x80 (drawn at 2x, like source/titleimg.h)."""
from PIL import Image, ImageEnhance, ImageOps
import os
here=os.path.dirname(os.path.abspath(__file__))
im=Image.open(os.path.join(here,'cover_bore_gba.jpg')).convert('RGB')
im=im.crop((380,330,1088,802))                     # the hand and the pipe, its bowl up where the glass bubble sits
im=im.resize((240,160),Image.LANCZOS)
g=ImageOps.autocontrast(im.convert('L'),cutoff=0.5)
g=ImageEnhance.Contrast(g).enhance(1.05)
ramp=[(0.0,(3,2,14)),(0.35,(8,40,120)),(0.6,(0,200,230)),(0.8,(250,60,170)),(1.0,(255,244,214))]
def lut(v):
    t=v/255.0
    for (a,ca),(b,cb) in zip(ramp,ramp[1:]):
        if t<=b:
            f=(t-a)/(b-a); return tuple(int(ca[i]+(cb[i]-ca[i])*f) for i in range(3))
    return ramp[-1][1]
col=Image.new('RGB',g.size)
col.putdata([lut(v) for v in g.getdata()])
col=col.resize((120,80),Image.LANCZOS)
q=col.quantize(16,method=Image.MEDIANCUT,dither=Image.NONE)
pal=q.getpalette()[:48]
out=["// GENERATED by tools/make_title_cc.py from the cover art: the BORE CREATOR title picture, 120x80, one hex digit per pixel, drawn at 2x.",
     "static const u16 titlePalCC[16]={ "+",".join("RGB(%d,%d,%d)"%(pal[i*3]>>3,pal[i*3+1]>>3,pal[i*3+2]>>3) for i in range(16))+" };",
     "static const char* const titleArtCC[80]={"]
px=list(q.getdata())
for y in range(80):
    out.append('"'+''.join('0123456789abcdef'[px[y*120+x]] for x in range(120))+'",')
out.append("};")
open(os.path.join(here,'..','source','titleimgcc.h'),'w').write('\n'.join(out)+'\n')
col.resize((480,320),Image.NEAREST).save('/tmp/cov/title_cc_preview.png')

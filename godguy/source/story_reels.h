// Each beat pairs a camera choice and visible action with a line the cast earns.
enum FilmSet {
    F_ORBIT, F_SHORE, F_STORM, F_VILLAGE, F_FORD, F_GATE, F_FORGE,
    F_HALL, F_ARCHIVE, F_HEARTH, F_THRONE, F_COUCH, F_PORCH, F_RUINS, F_SET_N
};
enum FilmProp {
    F_CUP, F_GOAT, F_HAMMER, F_SPOON, F_QUILL, F_LAMP, F_CROWN, F_LEAF,
    F_BREAD, F_MASK, F_CRUMB, F_SEED, F_PROP_N, F_NO_PROP=255
};
enum FilmActor {
    F_WISP, F_MIRA, F_GRUUL, F_ELOWEN, F_THORGRIM, F_HOLLOW, F_DAVE, F_ELDER,
    F_ACTOR_N, F_OFFSCREEN=255
};
enum FilmCamera { F_WIDE, F_NEAR, F_TRACK, F_HAND, F_INSERT };
// Action belongs to the shot, not the prop type. This prevents an object
// from hovering beside someone's head when the dialogue says they take it.
enum FilmAction {
    F_ACT_AUTO, F_ACT_TAKE, F_ACT_PASS, F_ACT_PUT,
    F_ACT_WORK, F_ACT_APPROACH
};
typedef struct {
    u8 place, camera, lead, other, prop, seconds, sound;
    const char *line;
    u8 action;
} FilmBeat;

#define SHOT(set,cam,a,b,prop,secs,sound,line) {F_##set,F_##cam,F_##a,F_##b,F_##prop,secs,sound,line,F_ACT_AUTO}
#define S(set,cam,a,b,prop,line) SHOT(set,cam,a,b,prop,7,0,line)
#define L(set,cam,a,b,prop,line) SHOT(set,cam,a,b,prop,8,0,line)
#define A(set,cam,a,b,prop,act,line) {F_##set,F_##cam,F_##a,F_##b,F_##prop,7,0,line,F_ACT_##act}



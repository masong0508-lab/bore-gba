#!/usr/bin/env python3
"""Generate 3DS-only high-detail *acting* cels, keeping DS assets untouched.

Each cel is drawn with the game's original 32-colour pixel-art palette at
native 40x48 detail. A 12-key acting set allows real anticipation, grips,
dialogue, listening, reactions, and controlled work instead of 4-pose loops.
Only the compressed 3DS binary contains these cels. No run-time allocation.
"""
from pathlib import Path
from story_art import WISP, MIRA_ELDER, SERIN, actor, canvas
import lz

WIDTH, HEIGHT = 40, 48
POSES = (
    ("idle", 0), ("walk", 2), ("walk", 6), ("reach", 0),
    ("talk", 0), ("talk", 4), ("listen", 0), ("react", 0),
    ("lift", 0), ("brace", 0), ("bow", 0), ("work", 0),
)
MAX_COMPRESSED_BYTES = 80 * 1024

def c_array(out, name, data):
    out.write("static const u8 %s[]={\n" % name)
    for i in range(0, len(data), 24):
        out.write("    " + ",".join(str(b) for b in data[i:i+24]) + ",\n")
    out.write("};\n")

def main():
    images = []
    for who in range(SERIN + 1):
        for pose, phase in POSES:
            cel = canvas((WIDTH, HEIGHT), 255)
            actor(cel, who, WIDTH // 2, HEIGHT, phase, HEIGHT, pose=pose)
            raw = cel.tobytes()
            assert len(raw) == WIDTH * HEIGHT
            assert all(pixel == 255 or pixel < 32 for pixel in raw)
            images.append(lz.encode(raw))
    total = sum(map(len, images))
    if total > MAX_COMPRESSED_BYTES:
        raise SystemExit("3DS film actor cels exceed %d bytes: %d" %
                         (MAX_COMPRESSED_BYTES, total))
    output = Path(__file__).resolve().parents[1] / "source" / "story_film_hq_data.h"
    with output.open("w", encoding="ascii", newline="\n") as out:
        out.write("// Generated by tools/make_story_hq.py. 3DS only.\n")
        out.write("#ifndef GG_STORY_FILM_HQ_DATA_H\n#define GG_STORY_FILM_HQ_DATA_H\n")
        out.write("#ifdef __3DS__\n")
        out.write("enum { FILM_HQ_W=40, FILM_HQ_H=48, FILM_HQ_N=12 };\n")
        for i, data in enumerate(images):
            c_array(out, "filmHqCast%d" % i, data)
        out.write("static const u8 *const filmHqCasts[]={\n")
        for i in range(0, len(images), 8):
            out.write("    " + ",".join("filmHqCast%d" % j for j in
                                       range(i, min(i+8, len(images)))) + ",\n")
        out.write("};\n#endif\n#endif\n")
    print("3DS film acting: %d cels, %d compressed bytes, %d per character" %
          (len(images), total, len(POSES)))

if __name__ == "__main__":
    main()

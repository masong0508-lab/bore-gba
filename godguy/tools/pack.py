import numpy as np
from PIL import Image
NCOL=50
im=Image.open('title_rgba.png'); a=np.array(im)
al=a[...,3]>0
ys,xs=np.nonzero(al); y0,y1,x0,x1=ys.min(),ys.max()+1,xs.min(),xs.max()+1
print('bbox',x0,y0,x1,y1)
# keep full width 256 so x placement is exact; trim vertically
a=a[:y1]; al=al[:y1]; H=y1; W=256
rgb=Image.fromarray(a[...,:3])
q=rgb.quantize(colors=NCOL,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
pal=np.array(q.getpalette()[:NCOL*3]).reshape(-1,3)
idx=np.array(q).astype(np.int32)+1
idx[~al]=0
used=sorted(set(idx.flatten())-{0}); print('colours',len(used))
# RLE (value,run<=255)
flat=idx.flatten().tolist(); rle=[]; i=0
while i<len(flat):
    v=flat[i]; n=1
    while i+n<len(flat) and flat[i+n]==v and n<255: n+=1
    rle+= [v,n]; i+=n
c5=lambda c: tuple(int(round(v*31/255)) for v in c)
pal15=[c5(p) for p in pal]
out=['// GENERATED by tools/make_title3d.py - the title-screen logo: BORE in silver chrome (the blunt taken out) over GODGUY in 3D stone slabs, after the Life of Brian poster.',
 '// %dx%d, %d colours (index 1..%d, 0 = clear), run-length coded as (colour, run) byte pairs; colour i is drawn with sub-palette entry TT_PAL0+i-1.'%(W,H,NCOL,NCOL),
 '#ifndef TITLE3D_H','#define TITLE3D_H','#define TT_W %d'%W,'#define TT_H %d'%H,'#define TT_N %d'%NCOL,'#define TT_PAL0 204',
 'static const unsigned short ttPal[TT_N]={ '+','.join('RGB15(%d,%d,%d)'%p for p in pal15)+' };',
 'static const unsigned short ttRle[%d]={'%(len(rle)//2)]
words=[(rle[k]<<8)|rle[k+1] for k in range(0,len(rle),2)]
line=''
rows=[]
for k in range(0,len(words),16): rows.append(','.join('0x%04x'%w for w in words[k:k+16]))
out.append(',\n'.join(rows)+' };')
out.append('#endif')
open('title3d.h','w').write('\n'.join(out)+'\n')
# preview of the quantised result
rec=np.zeros((H,W,4),np.uint8)
for v in used: rec[idx==v]=list(pal[v-1])+[255]
Image.fromarray(rec).save('title_quant.png')
print(len(words),'runs')

#!/usr/bin/env python3
"""Bake the chapter films and matching cast art into GodGuy's source."""
from pathlib import Path
from struct import pack

from story_art import PALETTE, MIRA_ELDER, cast_sprite
from story_shots import WIDTH, HEIGHT, SHOTS, render
from story_plates import SETS, PROPS, CEL_WIDTH, CEL_HEIGHT, CEL_N, PROP_SIZE, plate, plate_hd, cast_cel, prop
import lz


BLOCK_LIMIT = 16384
# The DS links the films below the 3 MiB save-buffer boundary.
DS_ASSET_LIMIT = 192 * 1024
FRAME_TICKS = 5
ORBIT_CLIPS = {"opening", "old_god", "finale"}


# A handful of visual hits borrow short effects from GodGuy's score.
CUES = {
    "opening": ((39, "FX_BLESS"), (81, "FX_BIRTH")),
    "first_folk": ((1, "FX_RAIN"), (61, "FX_STEP")),
    "roof": ((42, "FX_STEP"), (56, "FX_VILLAGE_FOUNDED")),
    "river_oath": ((35, "FX_STEP"), (61, "FX_PEACE")),
    "first_darkness": ((3, "FX_RAIN"), (29, "FX_MONSTER_SEEN")),
    "iron": ((12, "FX_STEP"), (50, "FX_STEP")),
    "stone": ((9, "FX_STEP"), (36, "FX_SETTLE")),
    "ink": ((50, "FX_PAINT"),),
    "one_fire": ((5, "FX_FIRE"), (60, "FX_PEACE")),
    "siege": ((1, "FX_WAR"), (22, "FX_LIGHTNING")),
    "city": ((72, "FX_STEP"),),
    "library": ((34, "FX_PAINT"),),
    "old_god": ((31, "FX_PEACE"), (80, "FX_STEP")),
    "godhood": ((41, "FX_BLESS"), (59, "FX_PEACE")),
    "finale": ((3, "FX_RAIN"), (40, "FX_PEACE")),
}


def delta(previous, current):
    """Zero ends the frame. Low bytes skip, high bytes pack color and run size."""
    i = 0
    data = bytearray()
    while i < len(current):
        end = i + 1
        if previous[i] == current[i]:
            stop = min(i + 127, len(current))
            while end < stop and previous[end] == current[end]:
                end += 1
            if end < len(current):
                data.append(end - i)
        else:
            color = current[i]
            stop = min(i + 128, len(current))
            while end < stop and current[end] == color:
                end += 1
            length = end - i
            if length <= 3:
                data.append(128 | ((length - 1) << 5) | color)
            else:
                data.extend((224 | color, length - 4))
        i = end
    data.append(0)
    return data


def encode(frames):
    blocks = []
    block = bytearray()
    prev = bytes([255]) * (WIDTH * HEIGHT)
    for frame in frames:
        commands = delta(prev, frame)
        if len(commands) > BLOCK_LIMIT:
            raise ValueError("A frame exceeds the decoder's scratch space")
        if block and len(block) + len(commands) > BLOCK_LIMIT:
            blocks.append(bytes(block))
            block.clear()
        block.extend(commands)
        prev = frame
    blocks.append(bytes(block))
    return b"".join(pack("<H", len(block)) + lz.encode(block) for block in blocks)


def c_array(out, name, ctype, values, width):
    out.write(f"static const {ctype} {name}[] = {{\n")
    for i in range(0, len(values), width):
        out.write("    " + ",".join(map(str, values[i:i+width])) + ",\n")
    out.write("};\n")


def main():
    clips = []
    orbit_clips = {}
    for name, title, count in SHOTS:
        frames = (render(name, t, flat=True).tobytes() for t in range(count))
        if name in ORBIT_CLIPS:
            orbit_clips[name] = encode(render(name, t).tobytes() for t in range(count))
        data = encode(frames)
        clips.append((name, title, count, data))
        print(f"{name:16s}{count/12:4.2f}s  {len(data):6,} bytes", flush=True)
    # Store idle, talk, blink and reaction cels. 255 is the transparency key.
    art = bytearray()
    portrait_offsets = []
    for who in range(MIRA_ELDER + 1):
        for talk, blink, react in ((False, False, False), (True, False, False),
                                   (False, True, False), (False, False, True)):
            portrait_offsets.append(len(art))
            art.extend(lz.encode(cast_sprite(who, talk, blink, react).tobytes()))
    sets = [lz.encode(plate(name, flat=True)) for name in SETS]
    wide_sets = [lz.encode(plate_hd(name)) for name in SETS]
    props = [lz.encode(prop(name)) for name in PROPS]
    cast_data = [lz.encode(cast_cel(who, cel)) for who in range(MIRA_ELDER + 1) for cel in range(CEL_N)]
    total = (sum(len(data) for _, _, _, data in clips) + len(art)
             + sum(map(len, sets + props + cast_data)))
    if total > DS_ASSET_LIMIT:
        raise ValueError(f"{total:,} bytes exceeds the DS cinematic asset budget")
    target = Path(__file__).resolve().parents[1] / "source" / "story_fmv_data.h"
    with target.open("w", encoding="ascii", newline="\n") as out:
        out.write("// Generated by tools/make_story_fmv.py.\n")
        out.write(f"enum {{ FMV_W = {WIDTH}, FMV_H = {HEIGHT}, FMV_TICKS = {FRAME_TICKS}, FMV_BLOCK_LIMIT = {BLOCK_LIMIT}, FMV_PORTRAIT_SIZE = 32, FMV_PORTRAIT_CELS = 4 }};\n")
        c_array(out, "fmvPalette", "u16",
                [(r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10) for r, g, b in PALETTE], 16)
        c_array(out, "fmvPortraitOffsets", "u16", portrait_offsets, 12)
        c_array(out, "fmvPortraits", "u8", art, 24)
        for name, _, _, data in clips:
            if name in orbit_clips:
                out.write("#ifdef __3DS__\n")
                c_array(out, f"fmv_{name}", "u8", orbit_clips[name], 24)
                out.write("#else\n")
            c_array(out, f"fmv_{name}", "u8", data, 24)
            if name in orbit_clips:
                out.write("#endif\n")
        out.write(f"enum {{ FILM_CEL_W = {CEL_WIDTH}, FILM_CEL_H = {CEL_HEIGHT}, "
                  f"FILM_CEL_N = {CEL_N}, FILM_PROP_SIZE = {PROP_SIZE} }};\n")
        for group, images in (("filmSet", sets), ("filmProp", props), ("filmCast", cast_data)):
            for i, image in enumerate(images):
                c_array(out, f"{group}{i}", "u8", image, 24)
            out.write(f"static const u8 *const {group}s[] = {{")
            out.write(",".join(f"{group}{i}" for i in range(len(images))))
            out.write("};\n")
        out.write("#ifdef __3DS__\n")
        for i, image in enumerate(wide_sets):
            c_array(out, f"filmWide{i}", "u8", image, 24)
        out.write("static const u8 *const filmWides[] = {")
        out.write(",".join(f"filmWide{i}" for i in range(len(wide_sets))))
        out.write("};\n#endif\n")
        out.write("static const FmvClip fmvClips[] = {\n")
        for name, title, count, _ in clips:
            cues = CUES[name]
            if len(cues) > 2 or any(not 0 <= frame < count for frame, _ in cues):
                raise ValueError(f"Invalid sound cues for {name}")
            hits = ", ".join(f"{{{frame}, {sound}}}" for frame, sound in cues)
            out.write(f'    {{fmv_{name}, {count}, "{title}", {{{hits}}}}},\n')
        out.write("};\n")
    print(f"{len(clips)} films, {sum(c for _, _, c, _ in clips)/12:g}s, "
          f"{total:,} shared bytes with portrait art, {sum(map(len, wide_sets)):,} 3DS-only bytes")


if __name__ == "__main__":
    main()
